import {Command} from '@oclif/core'

/**
 * Print a fully-commented `hordr:` block to stdout. Designed for
 * `hordr config >> .beans.yml` so a user can drop the whole customization
 * surface into their config in one go, then edit.
 *
 * Only documents knobs that actually exist in HordrConfigSchema. Output is
 * valid YAML when the comment lines are stripped.
 */
export default class Config extends Command {
  static description = 'Print a fully-commented hordr: block for .beans.yml. Pipe with `hordr config >> .beans.yml`.'
  static examples = ['<%= config.bin %> config']

  async run(): Promise<void> {
    this.log(EXAMPLE)
  }
}

const EXAMPLE = `# ─────────────────────────────────────────────────────────────────────────────
# hordr configuration — paste this block into your .beans.yml
# Generated by: hordr config   (safe to re-run; edits to an existing block
# must be merged by hand — this appends, it does not overwrite.)
# ─────────────────────────────────────────────────────────────────────────────
hordr:
  # Branch that worktrees branch from and PRs merge back into.
  primary_branch: develop

  # Harness binary used for any agent that does not set its own \`harness\`.
  # Flip this ONE line to repoint every persona at a different tool.
  #   opencode  (default)
  #   claude    (Anthropic Claude Code)
  #   codex     (OpenAI Codex)
  #   omp       (OpenMultiAgent — note: gets @AGENTS.md injected)
  # An explicit agent.harness below always wins over default_harness.
  default_harness: opencode

  # Optional: Agent Companies package (https://agentcompanies.io). When set,
  # agents/<role>/AGENTS.md bodies override the personas below with the
  # company's manifests. Env var HORDR_COMPANY_PATH takes precedence here.
  # company:
  #   path: /path/to/agent-company

  # One entry per role. Roles you omit fall back to built-in defaults
  # (implementer, tester, reviewer, merger) using default_harness. A bean's
  # \`assigned:\` frontmatter picks the role; unassigned beans use \`implementer\`.
  agents:
    implementer:
      harness: opencode      # omit (or set "") to inherit default_harness
      persona: |
        You implement ONE task bean assigned to you.
        Read the bean body below — it is your brief.
        When finished: commit code + bean together, then run: hordr done <bean-id>
        Then stop.

    tester:
      # harness inherited from default_harness
      persona: |
        You test ONE task bean. Write and run tests for the change.
        When tests pass: commit tests + bean together, then: hordr done <bean-id>

    reviewer:
      persona: |
        You review ONE task bean's implementation against its acceptance criteria.
        When the review passes: commit review notes + bean, then: hordr done <bean-id>

    # Add custom roles the same way; reference them from a bean via
    # \`assigned: <role>\` in its frontmatter.
`
